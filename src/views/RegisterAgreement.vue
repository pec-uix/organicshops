<script lang="ts">
import Vue from 'vue'

export default Vue.extend({
  name: 'RegisterAgreement',
  data() {
    return {
      hasAgreed: false,
    }
  },
  computed: {
    registerQuery(): Record<string, string> {
      const redirect = this.safeRedirect(this.$route.query.redirect)
      return redirect ? { redirect } : {}
    },
  },
  methods: {
    safeRedirect(value: unknown): string {
      const redirect = Array.isArray(value) ? value[0] : value
      if (typeof redirect !== 'string') return ''
      if (!redirect.startsWith('/') || redirect.startsWith('//')) return ''
      if (redirect === '/login' || redirect.startsWith('/login?')) return ''
      if (redirect === '/register' || redirect.startsWith('/register?')) return ''
      if (redirect === '/register-agreement' || redirect.startsWith('/register-agreement?')) return ''
      return redirect
    },
    agree() {
      if (!this.hasAgreed) return
      this.$router.push({ path: '/register', query: this.registerQuery })
    },
  },
})
</script>
